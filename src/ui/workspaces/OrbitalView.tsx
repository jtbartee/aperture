import { useRef } from 'react';
import { engine, useStore } from '../../state/store';
import { barBeats } from '../../core/time';
import { allowedPitches } from '../../theory/scales';
import { polarFromXY, xyFromPolar } from '../../interpret/orbital';
import { hexA, useStageCanvas } from '../canvas';
import { uid } from '../../core/ids';
import { hash32 } from '../../core/rng';

export function OrbitalView() {
  const project = useStore((s) => s.project);
  const ui = useStore((s) => s.ui);
  const geom = useRef({ cx: 0, cy: 0, R: 1 });
  const drag = useRef<{ x: number; y: number }[] | null>(null);
  const o = project.orbital;

  const { ref, invalidate } = useStageCanvas((ctx, w, h) => {
    const p = useStore.getState().project;
    const ob = p.orbital;
    const tr = p.tracks.find((t) => t.id === ob.trackId);
    ctx.fillStyle = '#0f1012';
    ctx.fillRect(0, 0, w, h);
    const R = Math.min(w, h) / 2 - 24;
    const cx = w / 2, cy = h / 2;
    geom.current = { cx, cy, R };
    const P = (a: number, r: number) => { const q = xyFromPolar(a, r); return [cx + (q.x - 0.5) * 2 * R, cy + (q.y - 0.5) * 2 * R] as const; };
    if (tr) {
      const pitches = allowedPitches(tr.pitch, p.settings.key, p.settings.scale, p.settings.customScale);
      pitches.forEach((m, i) => {
        const r = pitches.length > 1 ? i / (pitches.length - 1) : 0.5;
        const tonic = ((m - p.settings.key) % 12 + 12) % 12 === 0;
        ctx.strokeStyle = tonic ? 'rgba(224,164,88,0.35)' : 'rgba(255,255,255,0.05)';
        ctx.beginPath(); ctx.arc(cx, cy, Math.max(1, r * R), 0, Math.PI * 2); ctx.stroke();
      });
    }
    const beats = ob.bars * barBeats(p.settings.timeSig);
    for (let b = 0; b < beats; b++) {
      const [x, y] = P(b / beats, 1);
      ctx.strokeStyle = b % barBeats(p.settings.timeSig) === 0 ? '#3a3e46' : '#202328';
      ctx.beginPath(); ctx.moveTo(cx, cy); ctx.lineTo(x, y); ctx.stroke();
    }
    const col = tr?.color ?? '#e0a458';
    const drawPts = (pts: { x: number; y: number }[], c: string, wdt: number) => {
      ctx.strokeStyle = c; ctx.lineWidth = wdt; ctx.lineCap = 'round';
      if (pts.length === 1) { const [x, y] = P(pts[0].x, pts[0].y); ctx.fillStyle = c; ctx.beginPath(); ctx.arc(x, y, 4, 0, 7); ctx.fill(); return; }
      ctx.beginPath();
      pts.forEach((pt, i) => { const [x, y] = P(pt.x, pt.y); if (i) ctx.lineTo(x, y); else ctx.moveTo(x, y); });
      ctx.stroke();
    };
    for (const s of ob.strokes) drawPts(s.points, hexA(col, 0.9), 1.5 + s.brush.size);
    if (drag.current) drawPts(drag.current, col, 2);
    // notes generated by the orbit
    if (tr) {
      const pitches = allowedPitches(tr.pitch, p.settings.key, p.settings.scale, p.settings.customScale);
      ctx.fillStyle = hexA(col, 0.6);
      for (const n of tr.notes.filter((x) => x.origin === 'orbital')) {
        const a = (n.start % beats) / beats;
        const idx = pitches.indexOf(n.midi);
        const r = idx >= 0 ? idx / Math.max(1, pitches.length - 1) : 0.5;
        const [x, y] = P(ob.direction === 'cw' ? a : 1 - a, r);
        ctx.beginPath(); ctx.arc(x, y, 3, 0, 7); ctx.fill();
      }
    }
    // rotating playhead
    const pos = engine.position();
    const frac = (pos % beats) / beats;
    const a = ob.direction === 'cw' ? frac : 1 - frac;
    const [x, y] = P(a, 1.04);
    ctx.strokeStyle = '#f2c27b';
    ctx.lineWidth = 2;
    ctx.beginPath(); ctx.moveTo(cx, cy); ctx.lineTo(x, y); ctx.stroke();
    ctx.fillStyle = '#c9c6bf';
    ctx.font = '11px ui-sans-serif, system-ui';
    ctx.fillText(`${ob.direction === 'cw' ? 'clockwise ↻' : 'counter-clockwise ↺'} · ${ob.bars} bars per revolution`, 12, h - 12);
  }, [project, ui]);

  const toPolar = (e: { clientX: number; clientY: number }) => {
    const r = ref.current!.getBoundingClientRect();
    const g = geom.current;
    const x = 0.5 + (e.clientX - r.left - g.cx) / (2 * g.R);
    const y = 0.5 + (e.clientY - r.top - g.cy) / (2 * g.R);
    const pol = polarFromXY(x, y);
    return { x: pol.angle, y: pol.radius };
  };

  const commit = (pts: { x: number; y: number }[]) => {
    const st = useStore.getState();
    const id = uid('orb');
    const brush = { ...st.ui.brush, kind: st.ui.brush.kind === 'modulation' ? 'legato' as const : st.ui.brush.kind };
    st.commit((p) => ({ ...p, orbital: { ...p.orbital, strokes: [...p.orbital.strokes, { id, trackId: p.orbital.trackId, shape: pts.length === 1 ? 'dot' : 'freehand', brush, points: pts, seed: hash32(id) }] } }));
    st.regenerateOrbital();
  };

  return (
    <>
      <canvas ref={ref} role="img" aria-label="Orbital sequencer: angle is time, radius is pitch"
        onPointerDown={(e) => {
          (e.target as Element).setPointerCapture(e.pointerId);
          const pt = toPolar(e);
          if (ui.tool === 'eraser') {
            const st = useStore.getState();
            const hit = st.project.orbital.strokes.find((s) => s.points.some((q) => Math.abs(q.x - pt.x) < 0.02 && Math.abs(q.y - pt.y) < 0.06));
            if (hit) { st.commit((p) => ({ ...p, orbital: { ...p.orbital, strokes: p.orbital.strokes.filter((s) => s.id !== hit.id) } })); st.regenerateOrbital(); }
            return;
          }
          drag.current = [pt];
          invalidate();
        }}
        onPointerMove={(e) => { if (drag.current && ui.tool !== 'dot') { drag.current.push(toPolar(e)); invalidate(); } }}
        onPointerUp={() => { const d = drag.current; drag.current = null; if (d) commit(ui.tool === 'dot' ? d.slice(0, 1) : ui.tool === 'line' ? [d[0], d[d.length - 1]] : d); }} />
      {!o.strokes.length && <div className="overlay-msg passive"><div className="card"><h2>Orbital sequencer</h2><p>Draw inside the circle. The playhead sweeps around once every {o.bars} bars: where you draw in the circle sets <em>when</em>, distance from the centre sets <em>pitch</em> (rim = high). Uses the same brushes as the canvas.</p></div></div>}
    </>
  );
}
