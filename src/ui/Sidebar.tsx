import { useStore, type Tool } from '../state/store';
import type { BrushKind, Role, Track } from '../core/types';
import { ICurve, IDot, IEllipse, IEraser, IHand, ILine, IPencil, IPlus, IRect, ISelect } from './components/icons';
import { Section } from './components/controls';

const TOOLS: { id: Tool; label: string; key: string; icon: React.ReactNode }[] = [
  { id: 'pencil', label: 'Pencil', key: 'B', icon: <IPencil /> },
  { id: 'line', label: 'Line', key: 'L', icon: <ILine /> },
  { id: 'curve', label: 'Curve', key: 'C', icon: <ICurve /> },
  { id: 'dot', label: 'Dot', key: 'D', icon: <IDot /> },
  { id: 'rect', label: 'Rect', key: 'R', icon: <IRect /> },
  { id: 'ellipse', label: 'Ellipse', key: 'O', icon: <IEllipse /> },
  { id: 'eraser', label: 'Eraser', key: 'E', icon: <IEraser /> },
  { id: 'select', label: 'Select', key: 'V', icon: <ISelect /> },
];

const BRUSHES: { id: BrushKind; label: string; tip: string }[] = [
  { id: 'note', label: 'Note', tip: 'Discrete notes on every grid step the stroke crosses' },
  { id: 'legato', label: 'Legato', tip: 'Joins the stroke into a phrase; flat stretches sustain' },
  { id: 'arpeggio', label: 'Arpeggio', tip: 'Turns each beat of the stroke into an arpeggio' },
  { id: 'drone', label: 'Drone', tip: 'Holds the pitches the shape covers for its whole width' },
  { id: 'rhythm', label: 'Rhythm', tip: 'Short hits with metric accents; vertical scribbles ratchet' },
  { id: 'modulation', label: 'Modulation', tip: 'Draws automation (filter, pan, level, sends, effects)' },
];

export function sourceBadge(t: Track) {
  const g = t.generator ?? '';
  if (g.startsWith('image:')) return <span className="badge img" title="Derived from the imported image">IMG</span>;
  if (g.startsWith('pano:')) return <span className="badge img" title="Derived from the panorama">PANO</span>;
  if (g.startsWith('gen:')) return <span className="badge gen" title="Generated by the composer">GEN</span>;
  return <span className="badge draw" title="Hand-drawn / edited layer">DRAW</span>;
}

export function Sidebar() {
  const ui = useStore((s) => s.ui);
  const tracks = useStore((s) => s.project.tracks);
  const ws = useStore((s) => s.project.workspace);
  const st = useStore.getState();
  const drawingTools = ws === 'draw' || ws === 'orbital';
  return (
    <aside className="left" aria-label="Tools and layers">
      {drawingTools && (
        <Section title="Tools">
          <div className="tools" role="group" aria-label="Drawing tools">
            {TOOLS.filter((t) => ws === 'draw' || ['pencil', 'line', 'dot', 'eraser'].includes(t.id)).map((t) => (
              <button key={t.id} className={`btn ${ui.tool === t.id ? 'on' : ''}`} aria-pressed={ui.tool === t.id} title={`${t.label} (${t.key})`} onClick={() => st.setUi({ tool: t.id })}>
                {t.icon}<span>{t.label}</span>
              </button>
            ))}
          </div>
          {ws === 'draw' && (
            <div className="btnrow" style={{ marginTop: 6 }}>
              <button className={`btn small ${ui.tool === 'hand' ? 'on' : ''}`} title="Pan (H, or hold Space… or drag with the middle button)" onClick={() => st.setUi({ tool: 'hand' })}><IHand size={14} /> Pan</button>
              <button className={`btn small ${ui.showNotes ? 'on' : ''}`} aria-pressed={ui.showNotes} title="Show the notes each stroke produces (N)" onClick={() => st.setUi({ showNotes: !ui.showNotes })}>Note overlay</button>
            </div>
          )}
        </Section>
      )}
      {drawingTools && (
        <Section title="Brush">
          <div className="brushes" role="group" aria-label="Brush behaviour">
            {BRUSHES.map((b) => (
              <button key={b.id} className={`btn small ${ui.brush.kind === b.id ? 'on' : ''}`} aria-pressed={ui.brush.kind === b.id} title={b.tip} onClick={() => st.setUi({ brush: { ...ui.brush, kind: b.id }, tool: ['eraser', 'select', 'hand'].includes(ui.tool) ? 'pencil' : ui.tool })}>{b.label}</button>
            ))}
          </div>
          <p className="note">Brush settings live in the inspector → Source.</p>
        </Section>
      )}
      <Section title="Layers" right={
        <span style={{ display: 'flex', gap: 4 }}>
          <select className="sel" aria-label="Add layer with role" value="" onChange={(e) => { if (e.target.value) st.addTrack(e.target.value as Role); }} style={{ height: 22, fontSize: 11 }}>
            <option value="">+ Add…</option>
            {(['melody', 'bass', 'pad', 'chords', 'drone', 'arp', 'percussion', 'texture'] as Role[]).map((r) => <option key={r} value={r}>{r}</option>)}
          </select>
        </span>
      }>
        <div className="layers" role="list">
          {tracks.map((t) => (
            <button key={t.id} role="listitem" className="layer" aria-current={t.id === ui.selectedTrackId} onClick={() => st.setUi({ selectedTrackId: t.id, selNotes: [] })} title={`${t.name} · ${t.patch.name} · ${t.notes.length} notes`}>
              <span className="sw" style={{ background: t.color, opacity: t.mix.mute ? 0.35 : 1 }} />
              <span className="nm" style={{ opacity: t.mix.mute ? 0.5 : 1 }}>{t.name}</span>
              {sourceBadge(t)}
              <span className="ct">{t.notes.length}</span>
            </button>
          ))}
        </div>
        <div className="btnrow">
          <button className="btn small" onClick={() => st.addTrack('melody')}><IPlus size={13} /> Layer</button>
        </div>
      </Section>
      {ws === 'draw' && (
        <Section title="Canvas">
          <div className="btnrow">
            <button className="btn small" onClick={() => { if (confirm('Clear the drawing on this layer?')) st.clearLayer(ui.selectedTrackId); }}>Clear layer</button>
            <button className="btn small danger" onClick={() => { if (confirm('Clear the drawing on every layer?')) st.clearCanvas(); }}>Clear canvas</button>
          </div>
          <p className="note">Drawn strokes are kept separately from the notes they create — change key or scale and the notes re-pitch; move a stroke and its notes follow.</p>
        </Section>
      )}
    </aside>
  );
}
